from __future__ import annotations

import subprocess
import sys
import typing
from pathlib import Path
from runpy import run_path
from types import SimpleNamespace


def _write_generated_fixture(api_root: Path, *, canonical_has_create: bool) -> None:
    scores_dir = api_root / "scores"
    legacy_dir = api_root / "legacy" / "score_v1"
    legacy_types_dir = legacy_dir / "types"
    scores_dir.mkdir(parents=True)
    legacy_types_dir.mkdir(parents=True)

    canonical_methods = (
        "\n    def create(self):\n        pass\n"
        "\n    async def create(self):\n        pass\n"
        if canonical_has_create
        else ""
    )
    canonical_body = canonical_methods or "    pass\n"
    (scores_dir / "client.py").write_text(f"class ScoresClient:{canonical_body}")
    (legacy_dir / "client.py").write_text(
        "import typing\n"
        "from ...core.client_wrapper import AsyncClientWrapper, SyncClientWrapper\n\n"
        "class ScoreV1Client:\n"
        "    def delete(self):\n"
        "        pass\n\n"
        "class AsyncScoreV1Client:\n"
        "    async def delete(self):\n"
        "        pass\n"
    )
    (legacy_dir / "__init__.py").write_text(
        "# This file was auto-generated by Fern from our API Definition.\n"
    )
    (legacy_dir.parent / "__init__.py").write_text("__all__ = []\n")
    (legacy_types_dir / "__init__.py").write_text("__all__ = []\n")


def _run_postprocessor(api_root: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [
            sys.executable,
            "scripts/patch_generated_score_compat.py",
            "--api-root",
            str(api_root),
        ],
        check=False,
        capture_output=True,
        text=True,
    )


def test_postprocessor_adds_delegating_methods_and_type_aliases(tmp_path: Path) -> None:
    api_root = tmp_path / "api"
    _write_generated_fixture(api_root, canonical_has_create=True)

    result = _run_postprocessor(api_root)

    assert result.returncode == 0, result.stderr
    client = (api_root / "legacy" / "score_v1" / "client.py").read_text()
    assert "def create(" in client
    assert "async def create(" in client
    assert "CanonicalScoresClient(" in client
    assert "CanonicalAsyncScoresClient(" in client
    assert "client.scores.create" in client
    compile(client, "<generated-legacy-score-client>", "exec")

    response_alias = (
        api_root / "legacy" / "score_v1" / "types" / "create_score_response.py"
    ).read_text()
    assert (
        "from ....scores.types.create_score_response import CreateScoreResponse"
        in response_alias
    )
    assert (
        "CreateScoreResponse"
        in (api_root / "legacy" / "score_v1" / "__init__.py").read_text()
    )
    legacy_package = (api_root / "legacy" / "score_v1" / "__init__.py").read_text()
    assert "__all__ = [" in legacy_package
    assert "[*__all__" not in legacy_package
    assert "CreateScoreResponse" in (api_root / "legacy" / "__init__.py").read_text()

    second_result = _run_postprocessor(api_root)
    assert second_result.returncode == 0, second_result.stderr
    assert second_result.stdout.strip() == "No patch needed."


def test_postprocessor_fails_when_no_generated_create_exists(tmp_path: Path) -> None:
    api_root = tmp_path / "api"
    _write_generated_fixture(api_root, canonical_has_create=False)

    result = _run_postprocessor(api_root)

    assert result.returncode != 0
    assert "Neither generated score client defines" in result.stderr


def test_generated_sync_alias_delegates_to_canonical_client() -> None:
    postprocessor = run_path("scripts/patch_generated_score_compat.py")
    sync_create_method = postprocessor["SYNC_CREATE_METHOD"]
    calls: dict[str, object] = {}
    omitted = object()

    class FakeCreateScoreRequest:
        def __init__(self, **fields: object):
            self.fields = fields

    class FakeCanonicalScoresClient:
        def __init__(self, *, client_wrapper: object):
            calls["client_wrapper"] = client_wrapper

        def create(self, **kwargs: object) -> str:
            calls["kwargs"] = kwargs
            return "created"

    namespace = {
        "CanonicalScoresClient": FakeCanonicalScoresClient,
        "CreateScoreRequest": FakeCreateScoreRequest,
        "CreateScoreResponse": str,
        "CreateScoreSource": object,
        "CreateScoreValue": object,
        "OMIT": omitted,
        "RequestOptions": object,
        "ScoreDataType": object,
        "typing": typing,
    }
    exec(
        "class LegacyScoreClient:\n"
        "    def __init__(self, client_wrapper):\n"
        "        self._raw_client = SimpleNamespace("
        "_client_wrapper=client_wrapper)\n"
        f"{sync_create_method}",
        {**namespace, "SimpleNamespace": SimpleNamespace},
        namespace,
    )

    client_wrapper = object()
    legacy_client = namespace["LegacyScoreClient"](client_wrapper)
    response = legacy_client.create(name="quality", value=0.9, trace_id="trace-id")

    assert response == "created"
    assert calls["client_wrapper"] is client_wrapper
    kwargs = typing.cast(dict, calls["kwargs"])
    assert set(kwargs) == {"request", "request_options"}
    assert kwargs["request_options"] is None
    # Arguments that were not passed are left out of the request body.
    assert kwargs["request"].fields == {
        "name": "quality",
        "value": 0.9,
        "trace_id": "trace-id",
    }


def test_postprocessor_upgrades_a_previously_applied_alias(tmp_path: Path) -> None:
    postprocessor = run_path("scripts/patch_generated_score_compat.py")
    api_root = tmp_path / "api"
    _write_generated_fixture(api_root, canonical_has_create=True)
    assert _run_postprocessor(api_root).returncode == 0

    client_path = api_root / "legacy" / "score_v1" / "client.py"
    client = client_path.read_text()
    previous_imports = postprocessor["PREVIOUS_CLIENT_IMPORTS"][0]
    old_method = (
        "    def create(self, *, name, value):\n"
        '        """**Deprecated compatibility alias.** Use ``client.scores.create``."""\n'
        "        return CanonicalScoresClient().create(name=name, value=value)\n\n"
    )
    old_async_method = old_method.replace("def create", "async def create")
    client = client.replace(postprocessor["CLIENT_IMPORTS"], previous_imports)
    client = client.replace(postprocessor["SYNC_CREATE_METHOD"], old_method)
    client = client.replace(postprocessor["ASYNC_CREATE_METHOD"], old_async_method)
    client_path.write_text(client)

    result = _run_postprocessor(api_root)

    assert result.returncode == 0, result.stderr
    upgraded = client_path.read_text()
    assert upgraded.count("def create(") == 2
    assert "create(request=request" in upgraded
    assert "create(name=name, value=value)" not in upgraded
    assert "from ...scores.types.create_score_request import CreateScoreRequest" in (
        upgraded
    )
    compile(upgraded, "<upgraded-legacy-score-client>", "exec")
    assert _run_postprocessor(api_root).stdout.strip() == "No patch needed."
